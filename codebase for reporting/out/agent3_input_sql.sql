WITH client_trade_counts AS (
  SELECT 
    t.BUYER_CLIENT_ID AS CLIENT_ID,
    COUNT(*) AS trade_count
  FROM ATS.TRADES t
  WHERE t.ENTRY_DATETIME >= DATE '2024-01-01'
    AND t.ENTRY_DATETIME < DATE '2025-01-01'
  GROUP BY t.BUYER_CLIENT_ID
  ORDER BY trade_count DESC
  FETCH FIRST 1 ROWS ONLY
)
SELECT 
  c.CLIENT_ID,
  c.NAME
FROM ATS.EDS_CLIENTS c
JOIN client_trade_counts ctc ON c.CLIENT_ID = ctc.CLIENT_ID;